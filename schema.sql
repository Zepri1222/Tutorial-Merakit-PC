create table if not exists public.pc_questions (
 id bigint generated by default as identity primary key,
 name text not null default 'Pengunjung', category text not null default 'Lainnya',
 question text not null, answer text, status text not null default 'new' check(status in ('new','answered')),
 discord_message_id text, answered_at timestamptz, answered_by_discord text, created_at timestamptz not null default now()
);
alter table public.pc_questions add column if not exists answer text, add column if not exists discord_message_id text, add column if not exists answered_at timestamptz, add column if not exists answered_by_discord text;
alter table public.pc_questions enable row level security;
-- Hapus aturan akses dari versi panel-login terdahulu.
drop policy if exists "Anyone can submit a question" on public.pc_questions;
drop policy if exists "Admins can view questions" on public.pc_questions;
drop policy if exists "Admins can update question status" on public.pc_questions;
drop policy if exists "Anyone can submit PC questions" on public.pc_questions;
drop policy if exists "Public can read answered PC questions" on public.pc_questions;
create policy "Anyone can submit PC questions" on public.pc_questions for insert to anon,authenticated with check(char_length(question) between 8 and 2000 and char_length(coalesce(name,''))<=60);
create policy "Public can read answered PC questions" on public.pc_questions for select to anon,authenticated using(status='answered' and answer is not null);
grant insert,select on public.pc_questions to anon,authenticated;
grant usage,select on sequence public.pc_questions_id_seq to anon,authenticated;
